// Project Load & Tab Switching
async function loadProject(danceId = '1') {
  currentDanceId = String(danceId);
  project = null;

  if (currentDanceId === 'custom') {
    const localKey = 'dancing_cousins_custom_v1';
    try {
      const savedLocal = localStorage.getItem(localKey);
      if (savedLocal) {
        project = JSON.parse(savedLocal);
        if (project && project.items) {
          project.items.forEach(it => {
            if (customFileStore[it.id]) {
              it.audioUrl = URL.createObjectURL(customFileStore[it.id]);
            }
          });
        }
      }
    } catch (e) {}

    if (!project) {
      project = JSON.parse(JSON.stringify(CUSTOM_PROJECT_TEMPLATE));
    }

    renderTracks();
    updateTotalDurationDisplay();
    currentSeqIndex = 0;
    return;
  }

  const localKey = 'dancing_cousins_v5_d' + currentDanceId;
  let loadedFromLocal = false;

  try {
    const savedLocal = localStorage.getItem(localKey);
    if (savedLocal) {
      const parsed = JSON.parse(savedLocal);
      const isDance2 = (currentDanceId === '2');
      const hasD2Items = parsed.items && parsed.items.some(it => (it.id && it.id.startsWith('d2_')) || (it.fileName && it.fileName.startsWith('d2_')));
      if (isDance2 === hasD2Items && parsed.items && parsed.items.length > 0) {
        project = parsed;
        loadedFromLocal = true;
        console.log(`[LocalStorage] Restored Dance ${currentDanceId} timeline with ${project.items.length} tracks.`);
      } else {
        localStorage.removeItem(localKey);
      }
    }
  } catch (e) {
    try { localStorage.removeItem(localKey); } catch (_) {}
  }

  if (!project) {
    try {
      const res = await fetch(`/api/project?dance=${currentDanceId}`);
      if (res.ok) {
        project = await res.json();
      } else {
        throw new Error(`API status ${res.status}`);
      }
    } catch (err) {
      console.log(`[Static CDN] Loaded high-quality timeline for Dance ${currentDanceId}`);
      if (currentDanceId === '2') {
        project = JSON.parse(JSON.stringify(DANCE_2_DATA));
      } else {
        project = JSON.parse(JSON.stringify(DANCE_1_DATA));
      }
    }
  }

  // Ensure full audioUrl and segments array for each song
  if (project && project.items) {
    project.items.forEach((it, idx) => {
      if (!it.fullDurationSec) it.fullDurationSec = 240.0;
      if (!it.segments || !it.segments.length) {
        it.segments = [{ id: 'seg_1', startSec: parseFloat(it.startSec) || 0, endSec: parseFloat(it.endSec) || 45 }];
      }
      it.durationSec = it.segments.reduce((acc, s) => acc + Math.max(0, parseFloat(s.endSec) - parseFloat(s.startSec)), 0);
      if (!it.audioUrl) {
        it.audioUrl = `./audio/d${currentDanceId}/${idx + 1}_${it.fileName}`;
      }
    });
  }

  renderTracks();
  updateTotalDurationDisplay();
  currentSeqIndex = 0;
}

