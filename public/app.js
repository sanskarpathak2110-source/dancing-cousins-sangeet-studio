function getAudioDuration(url) {
  return new Promise((resolve) => {
    const audio = new Audio();
    audio.preload = 'metadata';
    audio.src = url;
    let resolved = false;
    audio.addEventListener('loadedmetadata', () => {
      if (!resolved) {
        resolved = true;
        resolve(audio.duration || 210.0);
      }
    });
    audio.addEventListener('error', () => {
      if (!resolved) {
        resolved = true;
        resolve(210.0);
      }
    });
    setTimeout(() => {
      if (!resolved) {
        resolved = true;
        resolve(210.0);
      }
    }, 3500);
  });
}

